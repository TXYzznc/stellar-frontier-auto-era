# 同一个任务ID会出现多次（不同批次各追加一条），所以按行收集而不是按 id 去重。
BY_TASK: dict[str, list[tuple[str, str, str]]] = {}
for _task_id, _status, _tag, _text in UPDATES:
    BY_TASK.setdefault(_task_id, []).append((_status, _tag, _text))


def main() -> int:
    dry_run = '--dry-run' in sys.argv
    book = openpyxl.load_workbook(BOOK)
    sheet = book[SHEET]

    headers = {sheet.cell(1, c).value: c for c in range(1, sheet.max_column + 1)}
    status_col = headers['状态']
    note_col = headers['备注']

    changed = 0
    seen = set()
    for row in range(2, sheet.max_row + 1):
        task_id = sheet.cell(row, 1).value
        entries = BY_TASK.get(task_id)
        if not entries:
            continue
        seen.add(task_id)

        old_status = sheet.cell(row, status_col).value
        note = sheet.cell(row, note_col).value
        status = old_status

        for entry_status, tag, text in entries:
            status = entry_status
            # 幂等：整条备注文本是否已经写过（标记字段只作说明，不写进正文）。
            if note is not None and text in str(note):
                continue
            note = text if not note else f'{note}\n{MARK}{text}'

        if old_status != status or sheet.cell(row, note_col).value != note:
            changed += 1
            print(f'{task_id}: 状态 {old_status} -> {status}')
            if not dry_run:
                sheet.cell(row, status_col).value = status
                sheet.cell(row, note_col).value = note

    missing = sorted(set(BY_TASK) - seen)
    if missing:
        print('警告：任务表里找不到这些任务ID：', missing)

    if dry_run:
        print(f'[dry-run] 将修改 {changed} 行')
        return 0

    book.save(BOOK)
    print(f'已写入 {BOOK}（修改 {changed} 行）')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
